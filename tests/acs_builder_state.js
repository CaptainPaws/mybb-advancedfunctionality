'use strict';
const assert = require('node:assert/strict');
const { DraftModel } = require('../inc/plugins/advancedfunctionality/addons/advancedcombatsystem/assets/builder.js');
const scope = { session_id: '1', encounter_id: '2', turn: { id: '3' }, scope_token: 'server-version' };
const a = { actor_id: '11', ability_key: 'claw', targets: ['20'], parameters: [] };
const pet = { actor_id: '12', ability_key: 'claw', targets: ['20'], parameters: { preserved: 0 } };
const m = new DraftModel();
m.add(a); m.add(pet); m.move(1, -1);
assert.deepEqual(m.actions, [pet, a]);
m.update(1, { ...a, targets: ['21'] }); m.remove(0);
m.text('Отыгрыш [b]героя[/b]');
const preview = m.preview(scope, 'hit');
assert.deepEqual(JSON.parse(preview.actions), [{ ...a, targets: ['21'] }]);
assert.equal(preview.scope_token, 'server-version');
assert.equal('ap_cost' in JSON.parse(preview.actions)[0], false);
const request = m.begin(scope, 'stable_operation_key_01');
assert.deepEqual(m.begin(scope, 'new_key_must_not_replace'), request);
assert.throws(() => m.text('Cannot edit ambiguous request'));
assert.throws(() => m.remove(0));
const reloaded = new DraftModel(); Object.assign(reloaded, JSON.parse(JSON.stringify(m)));
assert.deepEqual(reloaded.begin(scope, 'different'), request);
m.ack({ draft_id: '40', draft_version: '1' }); assert.equal(m.dirty, false);
m.text('Вторая вкладка');
assert.equal(m.begin(scope, 'save_next_version_02').expected_draft_version, '1');
m.restore({ draft_id: '40', draft_version: '2', prose: 'Серверная версия', actions: [pet] });
assert.equal(m.pending, null); assert.deepEqual(m.actions[0].parameters, { preserved: 0 });
assert.equal(m.version, '2'); assert.equal(m.prose, 'Серверная версия');
console.log('ACS builder state: ordered add/edit/remove, preserved parameters, draft/preview serialization, stable retry and restore passed');
